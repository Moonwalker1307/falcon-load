using System.Globalization;
using System.Net;
using System.Text;
using FalconLoad.Core.Metrics;
using static FalconLoad.Core.Reports.ReportFormat;

namespace FalconLoad.Core.Reports;

/// <summary>
/// Renders a finished run as one self-contained HTML page: no scripts, no fonts and no requests to other sites, so it can
/// be attached to a CI job, mailed or opened years later. It shows results and the test's name, load and environment name
/// only; never the requests' headers or bodies, which can hold tokens, and an environment's values.
/// </summary>
public static class HtmlReport
{
    private const int MaxErrorRows = 50;

    public static string Render(RunExport export, RunVerdict verdict)
    {
        var s = export.Results;
        var plan = export.Plan;
        var html = new StringBuilder(16 * 1024);
        var result = Result(s, verdict);

        html.Append("<!doctype html>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\">\n");
        html.Append("<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n");
        html.Append("<meta name=\"color-scheme\" content=\"dark\">\n");
        html.Append($"<title>{E(plan.Name)}: {result.Text} · falcon-load report</title>\n<style>{Css}</style>\n</head>\n<body>\n<main>\n");

        html.Append("<header>\n<div class=\"eyebrow\">falcon-load report</div>\n");
        html.Append($"<div class=\"title-row\"><h1>{E(plan.Name)}</h1><span class=\"badge {result.Css}\">{result.Text}</span></div>\n<p class=\"meta\">");
        html.Append(string.Join(" · ", Meta(export)));
        html.Append("</p>\n</header>\n");

        AppendVerdict(html, s, verdict);
        AppendStats(html, s);
        AppendCharts(html, s);
        AppendLatency(html, s);
        AppendStatusCodes(html, s);
        AppendSteps(html, s);
        AppendChecks(html, s);
        AppendErrors(html, s);

        html.Append("<footer>Generated by falcon-load. Run ").Append(export.Id).Append("</footer>\n</main>\n</body>\n</html>\n");
        return html.ToString();
    }

    private static (string Text, string Css) Result(LoadTestSnapshot s, RunVerdict verdict) =>
        verdict.Passed ? ("Passed", "badge-pass")
        : s.State == RunState.Cancelled ? ("Interrupted", "badge-fail")
        : ("Failed", "badge-fail");

    private static IEnumerable<string> Meta(RunExport export)
    {
        var s = export.Results;
        yield return $"Started {export.StartedAt.UtcDateTime:yyyy-MM-dd HH:mm:ss} UTC";
        yield return $"{State(s.State)} after {Duration(s.Elapsed)}";
        yield return E(DescribeProfile(export.Plan.Profile));
        if (!string.IsNullOrWhiteSpace(export.Plan.Environment))
        {
            yield return $"Environment <strong>{E(export.Plan.Environment)}</strong>";
        }

        if (!string.IsNullOrWhiteSpace(export.Machine))
        {
            yield return $"Machine {E(export.Machine)}";
        }

        if (s.Auth is { } auth)
        {
            yield return FormattableString.Invariant($"OAuth2, {auth.TokensFetched:#,0} {(auth.TokensFetched == 1 ? "token" : "tokens")} fetched{(auth.FailedFetches > 0 ? $", {auth.FailedFetches:#,0} token requests failed" : string.Empty)}");
        }
    }

    private static string State(RunState state) => state switch
    {
        RunState.Completed => "Completed",
        RunState.Cancelled => "Stopped",
        RunState.Failed => "Failed",
        _ => state.ToString(),
    };

    private static void AppendVerdict(StringBuilder html, LoadTestSnapshot s, RunVerdict verdict)
    {
        html.Append("<section>\n<h2>Result</h2>\n");
        if (s.FailureReason is not null)
        {
            html.Append($"<p class=\"alert\">The run failed: {E(s.FailureReason)}</p>\n");
        }

        html.Append("<table>\n<thead><tr><th scope=\"col\">Status</th><th scope=\"col\">Condition</th><th scope=\"col\">Detail</th></tr></thead>\n<tbody>\n");
        foreach (var check in verdict.Checks)
        {
            var detail = check.Kind == RunVerdict.ThresholdKind
                ? Threshold(s, check)
                : check.Message ?? string.Empty;
            html.Append($"<tr><td><span class=\"{(check.Passed ? "pass" : "fail")}\">{(check.Passed ? "Pass" : "Fail")}</span></td><td>{E(check.Name)}</td><td>{E(detail)}</td></tr>\n");
        }

        html.Append("</tbody>\n</table>\n");
        if (s.Thresholds.Count == 0)
        {
            html.Append("<p class=\"note\">This test has no thresholds, so it passes when the run completes and no request fails.</p>\n");
        }

        html.Append("</section>\n");
    }

    private static string Threshold(LoadTestSnapshot s, VerdictCheck check)
    {
        var threshold = s.Thresholds.FirstOrDefault(t => t.Name == check.Name);
        return threshold is null ? string.Empty
            : threshold.Actual is { } actual ? $"measured {Value(actual, threshold.Unit)}"
            : "nothing was measured";
    }

    private static void AppendStats(StringBuilder html, LoadTestSnapshot s)
    {
        html.Append("<section class=\"stats\" aria-label=\"Summary\">\n");
        Stat(html, "Requests", Count(s.TotalRequests), $"{Count(s.SuccessfulRequests)} succeeded");
        Stat(html, "Throughput", Rate(s.RequestsPerSecond) + " req/s", "average over the run");
        Stat(html, "Error rate", Percent(s.ErrorRate), $"{Count(s.FailedRequests)} failed");
        Stat(html, "p95 latency", Ms(s.Latency.P95Ms), $"mean {Ms(s.Latency.MeanMs)}");
        Stat(html, "Data", Bytes(s.BytesReceived), $"received, {Bytes(s.BytesSent)} sent");
        html.Append("</section>\n");
    }

    private static void Stat(StringBuilder html, string label, string value, string sub) =>
        html.Append($"<div class=\"stat\"><div class=\"label\">{E(label)}</div><div class=\"value\">{E(value)}</div><div class=\"sub\">{E(sub)}</div></div>\n");

    private static void AppendCharts(StringBuilder html, LoadTestSnapshot s)
    {
        if (s.Timeline.Count < 2)
        {
            return;
        }

        html.Append("<section>\n<h2>Over time</h2>\n<div class=\"charts\">\n");
        Chart(html, "Requests per second", "req/s", s.Timeline,
        [
            new("Requests", Yellow, s.Timeline.Select(p => (double)p.Requests).ToList()),
            new("Failed", Red, s.Timeline.Select(p => (double)p.Failures).ToList()),
        ], v => Rate(v));
        Chart(html, "Latency", "ms", s.Timeline,
        [
            new("p95", Yellow, s.Timeline.Select(p => p.P95LatencyMs).ToList()),
            new("Mean", Muted, s.Timeline.Select(p => p.MeanLatencyMs).ToList()),
        ], v => Ms(v));
        html.Append("</div>\n</section>\n");
    }

    private const string Yellow = "#FFD52A";
    private const string Red = "#F07171";
    private const string Muted = "#A8B0C4";

    private sealed record Line(string Name, string Color, IReadOnlyList<double> Values);

    /// <summary>A hand-written SVG line chart with one value per second of the run.</summary>
    private static void Chart(StringBuilder html, string title, string unit, IReadOnlyList<TimelinePoint> timeline, Line[] lines, Func<double, string> label)
    {
        const double width = 600, height = 220, left = 56, right = 12, top = 12, bottom = 28;
        var plotWidth = width - left - right;
        var plotHeight = height - top - bottom;
        var max = NiceMax(lines.SelectMany(l => l.Values).DefaultIfEmpty(0).Max());
        var first = timeline[0].Second;
        var span = Math.Max(1, timeline[^1].Second - first);

        double X(int second) => left + (second - first) / (double)span * plotWidth;
        double Y(double value) => top + plotHeight - value / max * plotHeight;

        var summary = string.Join("; ", lines.Select(l => $"{l.Name} peaks at {label(l.Values.Max())}"));
        html.Append($"<figure>\n<figcaption>{E(title)}</figcaption>\n");
        html.Append($"<svg viewBox=\"0 0 {Num(width)} {Num(height)}\" role=\"img\" aria-label=\"{E(title)}: {E(summary)}\">\n");
        for (var i = 0; i <= 4; i++)
        {
            var value = max * i / 4;
            var y = Y(value);
            html.Append($"<line class=\"grid\" x1=\"{Num(left)}\" x2=\"{Num(width - right)}\" y1=\"{Num(y)}\" y2=\"{Num(y)}\"/>");
            html.Append($"<text class=\"tick\" x=\"{Num(left - 6)}\" y=\"{Num(y + 3.5)}\" text-anchor=\"end\">{E(label(value))}</text>\n");
        }

        foreach (var (second, anchor) in new[] { (first, "start"), (first + span / 2, "middle"), (first + span, "end") })
        {
            html.Append($"<text class=\"tick\" x=\"{Num(X(second))}\" y=\"{Num(height - 8)}\" text-anchor=\"{anchor}\">{second}s</text>\n");
        }

        foreach (var line in lines)
        {
            var points = string.Join(' ', timeline.Select((p, i) => $"{Num(X(p.Second))},{Num(Y(line.Values[i]))}"));
            html.Append($"<polyline fill=\"none\" stroke=\"{line.Color}\" stroke-width=\"2\" stroke-linejoin=\"round\" points=\"{points}\"/>\n");
        }

        html.Append("</svg>\n<div class=\"legend\">");
        html.Append(string.Join(string.Empty, lines.Select(l => $"<span><i style=\"background:{l.Color}\"></i>{E(l.Name)}</span>")));
        html.Append($"<span class=\"unit\">{E(unit)}</span></div>\n</figure>\n");
    }

    /// <summary>Rounds up to 1, 2, 2.5, 5 or 10 times a power of ten, so the grid labels are round numbers.</summary>
    private static double NiceMax(double value)
    {
        if (value <= 0 || double.IsNaN(value))
        {
            return 1;
        }

        var magnitude = Math.Pow(10, Math.Floor(Math.Log10(value)));
        foreach (var step in new[] { 1, 2, 2.5, 5, 10 })
        {
            if (value <= step * magnitude)
            {
                return step * magnitude;
            }
        }

        return 10 * magnitude;
    }

    private static void AppendLatency(StringBuilder html, LoadTestSnapshot s)
    {
        var l = s.Latency;
        html.Append("<section>\n<h2>Latency</h2>\n<table class=\"num\">\n<thead><tr>");
        foreach (var name in new[] { "Min", "Mean", "p50", "p90", "p95", "p99", "Max" })
        {
            html.Append($"<th scope=\"col\">{name}</th>");
        }

        html.Append("</tr></thead>\n<tbody><tr>");
        foreach (var ms in new[] { l.MinMs, l.MeanMs, l.P50Ms, l.P90Ms, l.P95Ms, l.P99Ms, l.MaxMs })
        {
            html.Append($"<td>{Ms(ms)}</td>");
        }

        html.Append("</tr></tbody>\n</table>\n</section>\n");
    }

    private static void AppendStatusCodes(StringBuilder html, LoadTestSnapshot s)
    {
        if (s.StatusCodes.Count == 0)
        {
            return;
        }

        html.Append("<section>\n<h2>Status codes</h2>\n<table class=\"num\">\n<thead><tr><th scope=\"col\">Status</th><th scope=\"col\">Responses</th><th scope=\"col\">Share</th></tr></thead>\n<tbody>\n");
        var responses = s.StatusCodes.Values.Sum();
        foreach (var (code, count) in s.StatusCodes.OrderBy(c => c.Key, StringComparer.Ordinal))
        {
            html.Append($"<tr><td>{E(code)}</td><td>{Count(count)}</td><td>{Percent(responses == 0 ? 0 : (double)count / responses)}</td></tr>\n");
        }

        html.Append("</tbody>\n</table>\n</section>\n");
    }

    private static void AppendSteps(StringBuilder html, LoadTestSnapshot s)
    {
        if (s.Steps.Count < 2)
        {
            return;
        }

        html.Append("<section>\n<h2>Per request</h2>\n<table class=\"num\">\n<thead><tr><th scope=\"col\">Request</th><th scope=\"col\">Requests</th><th scope=\"col\">Failed</th><th scope=\"col\">Mean</th><th scope=\"col\">p95</th><th scope=\"col\">p99</th></tr></thead>\n<tbody>\n");
        foreach (var step in s.Steps)
        {
            html.Append($"<tr><td>{E(step.Name)}</td><td>{Count(step.Requests)}</td><td>{Count(step.Failures)}</td><td>{Ms(step.Latency.MeanMs)}</td><td>{Ms(step.Latency.P95Ms)}</td><td>{Ms(step.Latency.P99Ms)}</td></tr>\n");
        }

        html.Append("</tbody>\n</table>\n</section>\n");
    }

    private static void AppendChecks(StringBuilder html, LoadTestSnapshot s)
    {
        if (s.Checks.Count == 0)
        {
            return;
        }

        html.Append("<section>\n<h2>Response checks</h2>\n<table class=\"num\">\n<thead><tr><th scope=\"col\">Check</th><th scope=\"col\">Passed</th><th scope=\"col\">Failed</th></tr></thead>\n<tbody>\n");
        foreach (var check in s.Checks)
        {
            html.Append($"<tr><td>{E(check.Name)}</td><td>{Count(check.Passed)}</td><td>{Count(check.Failed)}</td></tr>\n");
        }

        html.Append("</tbody>\n</table>\n</section>\n");
    }

    private static void AppendErrors(StringBuilder html, LoadTestSnapshot s)
    {
        if (s.Errors.Count == 0)
        {
            return;
        }

        html.Append("<section>\n<h2>Errors</h2>\n<table class=\"num\">\n<thead><tr><th scope=\"col\">Error</th><th scope=\"col\">Count</th></tr></thead>\n<tbody>\n");
        foreach (var error in s.Errors.Take(MaxErrorRows))
        {
            html.Append($"<tr><td>{E(error.Message)}</td><td>{Count(error.Count)}</td></tr>\n");
        }

        html.Append("</tbody>\n</table>\n");
        if (s.Errors.Count > MaxErrorRows)
        {
            html.Append($"<p class=\"note\">and {s.Errors.Count - MaxErrorRows} other kinds of error</p>\n");
        }

        html.Append("</section>\n");
    }

    private static string E(string? text) => WebUtility.HtmlEncode(text ?? string.Empty);

    private static string Num(double value) => value.ToString("0.##", CultureInfo.InvariantCulture);

